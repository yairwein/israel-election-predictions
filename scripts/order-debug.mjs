import { chromium, devices } from 'playwright';
const base = process.argv[2];
const b = await chromium.launch();
const ctx = await b.newContext({ ...devices['iPhone 13'], locale: 'he-IL' });
const page = await ctx.newPage();
const pid = () => page.evaluate(() => fetch('/api/me').then((r) => r.json()).then((d) => d.publicId));
const names = async () => (await page.locator('.parties .he').allTextContents()).slice(0, 4).join(' · ');
await page.goto(base + '/predict', { waitUntil: 'networkidle' });
console.log('dev voter     ', await pid(), '|', await names());
await page.getByPlaceholder('התחברות כמצביע בדיקה (שם)').fill(`dbg-${Date.now()}`);
await page.locator('.devbar button[type=submit]').click();
await page.waitForLoadState('networkidle');
await page.waitForTimeout(500);
console.log('after sign-in ', await pid(), '|', await names());
await page.reload({ waitUntil: 'networkidle' });
console.log('after reload  ', await pid(), '|', await names());
await b.close();
